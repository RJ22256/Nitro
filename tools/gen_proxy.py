"""Generates the proxy export thunks for NitroHook.dll.

The hook DLL can be installed into a game folder as dxgi.dll, d3d9.dll or
version.dll. It exports the union of those DLLs' functions; at load time it
fills in the jump table for whichever system DLL it is standing in for.

Run: python tools/gen_proxy.py  (rewrites hook/proxy_thunks.asm,
hook/exports.def and hook/proxy_table.inc)
"""
from pathlib import Path

PROXIES = {
    "dxgi.dll": [
        "ApplyCompatResolutionQuirking", "CompatString", "CompatValue",
        "CreateDXGIFactory", "CreateDXGIFactory1", "CreateDXGIFactory2",
        "DXGID3D10CreateDevice", "DXGID3D10CreateLayeredDevice",
        "DXGID3D10GetLayeredDeviceSize", "DXGID3D10RegisterLayers",
        "DXGIDeclareAdapterRemovalSupport", "DXGIDisableVBlankVirtualization",
        "DXGIDumpJournal", "DXGIGetDebugInterface1", "DXGIReportAdapterConfiguration",
        "PIXBeginCapture", "PIXEndCapture", "PIXGetCaptureState",
        "SetAppCompatStringPointer", "UpdateHMDEmulationStatus", "DXGIRevertToSxS",
    ],
    "d3d9.dll": [
        "D3DPERF_BeginEvent", "D3DPERF_EndEvent", "D3DPERF_GetStatus",
        "D3DPERF_QueryRepeatFrame", "D3DPERF_SetMarker", "D3DPERF_SetOptions",
        "D3DPERF_SetRegion", "DebugSetLevel", "DebugSetMute",
        "Direct3D9EnableMaximizedWindowedModeShim", "Direct3DCreate9",
        "Direct3DCreate9Ex", "Direct3DCreate9On12", "Direct3DCreate9On12Ex",
        "Direct3DShaderValidatorCreate9", "PSGPError", "PSGPSampleTexture",
    ],
    "version.dll": [
        "GetFileVersionInfoA", "GetFileVersionInfoByHandle", "GetFileVersionInfoExA",
        "GetFileVersionInfoExW", "GetFileVersionInfoSizeA", "GetFileVersionInfoSizeExA",
        "GetFileVersionInfoSizeExW", "GetFileVersionInfoSizeW", "GetFileVersionInfoW",
        "VerFindFileA", "VerFindFileW", "VerInstallFileA", "VerInstallFileW",
        "VerLanguageNameA", "VerLanguageNameW", "VerQueryValueA", "VerQueryValueW",
    ],
}

root = Path(__file__).resolve().parent.parent / "hook"
entries = [(dll, name) for dll, names in PROXIES.items() for name in names]

asm = [
    "; GENERATED by tools/gen_proxy.py - do not edit.",
    "; Each export jumps through g_proxyProcs[i], filled in by DllMain.",
    "",
    ".data",
    "PUBLIC g_proxyProcs",
    f"g_proxyProcs QWORD {len(entries)} DUP(0)",
    "",
    ".code",
    "",
]
for i, (_, name) in enumerate(entries):
    asm += [f"Thunk_{name} PROC", f"    jmp QWORD PTR [g_proxyProcs + {i * 8}]", f"Thunk_{name} ENDP", ""]
asm.append("END")
(root / "proxy_thunks.asm").write_text("\n".join(asm) + "\n")

deff = ["; GENERATED by tools/gen_proxy.py - do not edit.", "EXPORTS"]
deff += [f"    {name}=Thunk_{name}" for _, name in entries]
deff += ["    Nitro_InitHooks", "    Nitro_Marker DATA"]
(root / "exports.def").write_text("\n".join(deff) + "\n")

inc = ["// GENERATED by tools/gen_proxy.py - do not edit.",
       f"constexpr size_t kProxyCount = {len(entries)};",
       "const ProxyEntry kProxyEntries[kProxyCount] = {"]
inc += [f'    {{L"{dll}", "{name}"}},' for dll, name in entries]
inc.append("};")
(root / "proxy_table.inc").write_text("\n".join(inc) + "\n")
print(f"{len(entries)} proxy exports written")
